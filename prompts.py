"""
All new_arch prompt templates in one file (easy to inspect/audit, per the
approved file tree). Every function that interpolates the raw hate comment
wraps it with safety.wrap_untrusted_text() first (prompt-injection guard -
the comment is data to analyze, never instructions to obey).

Academic honesty note (same as the old project): paper-inspired adaptation,
not exact replication. No prompt is copied word-for-word from any paper.

Persona framing: candidates generated by persona_generator_agent.py are
always professional/expert framings (e.g. "rhetoric analyst", "family
counsellor") - never an identity impersonation of a marginalized group and
never a persona that literally self-describes as "pro-hate". The Prosecutor
PROMPT (build_prosecutor_prompt) is what asks whichever persona was selected
for that role to analytically construct the harmful claim's strongest
internal logic - this is a deliberate, explicit, internal-only exception to
"never argue for the hateful claim", scoped strictly to this one prompt and
never surfaced to the end user (see safety.py).
"""
from safety import wrap_untrusted_text, BASE_SAFETY_RULES

# ---------------------------------------------------------------------------
# 1. Case Analysis Agent
# ---------------------------------------------------------------------------
def build_case_analysis_prompt(comment: str, language_hint: str = None, region_hint: str = None) -> str:
    return f"""You are a hate-speech case analysis agent focused on homophobia and transphobia,
operating across English, Tamil, Basque, Spanish, and Italian.

{wrap_untrusted_text(comment)}

Language hint from caller (may be None/unreliable - verify against the text): {language_hint}
Region hint from caller (manual selection, if any - trust this over any inference): {region_hint}

Analyze the comment for:
- language (en/ta/eu/es/it)
- target_group (e.g. "gay men", "trans women", "LGBT+ people generally")
- hate_category: one of "homophobia", "transphobia", "mixed", "unclear", "unsupported_category"
- intent: list drawn from {{mockery, dehumanization, moral_panic, religious_justification,
  pseudoscientific_claim, family_or_parenting_argument, criminalization, exclusion,
  stereotyping, threat, just_asking_questions, sarcasm, dog_whistle, other}} - not
  restricted to this list if something else fits better
- strategy_hint: list drawn from {{factual_correction, empathy_based_response,
  logical_inconsistency, myth_correction, cultural_contextualization, rights_based_framing,
  harm_reduction, de_escalation, combination}}
- hate_type: "explicit" (overt slur/direct hateful statement) or "implicit" (coded language,
  dog whistle, euphemism, rhetorical question, sarcasm, "just asking questions")
- confidence (0.0-1.0) in this analysis
- hidden_claim: for implicit hate, the underlying claim/assumption being smuggled in (null if explicit/none)
- evidence_topics: list of topics a fact-checker would need to verify (e.g. "adoption outcomes research",
  "historical legal status"); [] if none
- cultural_context_needed (true/false): does answering this well require cultural/regional context?
- safety_notes: anything a downstream writer should be careful about (slurs present, threat language, etc.)
- rationale: 1-3 sentence explanation of the above

{BASE_SAFETY_RULES}
Additional rule for this step: do not repeat slurs or hateful phrases in your own output -
describe them abstractly instead.

Region suggestion (be careful here):
- Only suggest a region/country if the text contains STRONG, EXPLICIT evidence (e.g. a named
  place, a locally-specific law, an explicit self-identification) - not a guess from language,
  name, religion, ethnicity, or generic cultural reference.
- If there is no such strong explicit evidence, set region=null, country=null, confidence=0.0,
  and rationale="no strong explicit regional evidence in the text".
- Never infer a country/region from the language alone (e.g. do not assume Spanish->Spain,
  Tamil->India, English->UK/Ireland - LT-EDI Tamil/English data is Indian, but this must come
  from confirmed dataset/region metadata, never from language choice by itself).

Output JSON only, matching this schema exactly:
{{
  "language": "en",
  "target_group": "...",
  "hate_category": "...",
  "intent": ["..."],
  "strategy_hint": ["..."],
  "hate_type": "explicit",
  "confidence": 0.0,
  "hidden_claim": null,
  "evidence_topics": ["..."],
  "cultural_context_needed": true,
  "region_suggestion": {{"region": null, "country": null, "confidence": 0.0, "rationale": "..."}},
  "safety_notes": ["..."],
  "rationale": "..."
}}"""


