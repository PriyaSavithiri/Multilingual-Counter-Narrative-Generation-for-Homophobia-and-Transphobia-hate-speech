# 5. Evidence claim/query formulation (used by evidence_verifier.py, called
#    from inside the Defender's turn - never a standalone post-hoc stage)
# ---------------------------------------------------------------------------
def build_claim_query_prompt(claim: str, language: str) -> str:
    return f"""Given this factual claim that needs verification: "{claim}"
(the claim originates from a comment/response in language "{language}")

Generate:
1. A retrieval query IN THE ORIGINAL LANGUAGE ({language}) that would find evidence relevant
   to this exact claim.
2. A semantically-equivalent retrieval query IN ENGLISH for the same claim (do not translate
   the claim itself elsewhere - only these two query variants).

Do not assume a country or region from the language - keep both queries topic-focused, not
region-specific, unless the claim itself names a specific place.

Output JSON only:
{{"input_language_query": "...", "english_query": "..."}}"""


# ---------------------------------------------------------------------------
# 6. Judge / Critic Agent (single synthesis, reviews evidence without
#    rerunning a duplicate fact-debate)
# ---------------------------------------------------------------------------
def build_judge_prompt(comment: str, case_analysis: dict, persona_selection: dict,
                        router_decision: dict, debate_rounds: list, region_context: str = "unknown") -> str:
    return f"""You are the Judge/Critic - the sole synthesis step before the final counter-narrative
is written. You review the complete debate (including the internal Prosecutor analysis, which
you may read for context but which must NEVER appear in your final_response_plan or anywhere
that reaches the end user) and produce a plan for the Final Counter-Narrative Agent.

{wrap_untrusted_text(comment)}

Case analysis: {case_analysis}
Persona selection: {persona_selection}
Routing decision: {router_decision}
Region context (confirmed or "unknown"): {region_context}
Complete debate history (internal - includes Prosecutor content for your review only): {debate_rounds}

Assess:
- Relevance to the actual comment and correct interpretation of explicit/implicit hate
- Whether the hidden claim (if implicit) was adequately addressed
- Factual grounding and evidence quality (do not accept unsupported claims as fact)
- Cultural awareness and appropriateness for the region context (or neutral if unknown)
- Safety, non-escalation, and risk of repeating harmful language or amplifying stereotypes
- Logical strength and same-language compliance
- Whether any claims should be rejected (unsupported / unsafe / irrelevant /
  culturally_inappropriate / repetitive) - list each with a reason

Do not simply copy the Defender's response - synthesize your own plan.

IMPORTANT: "selected_language" MUST be exactly the same value as the "language" field already
given above in Case analysis (in this case: "{case_analysis.get('language')}") - this is a fixed
fact already determined upstream, not something for you to re-decide or guess. Copy it exactly,
character for character. Do not default to English or any other language.

CRITICAL: "core_claim_to_counter" and "final_response_plan" MUST be about THIS SPECIFIC case only
- the actual hate comment above, target group "{case_analysis.get('target_group')}", and hate
category "{case_analysis.get('hate_category')}". Do NOT describe any other scenario, product,
service, or topic under any circumstances, even if the debate history above feels long or
repetitive - stay strictly grounded in the exact case given here from start to finish.

{BASE_SAFETY_RULES}

Output JSON only:
{{
  "selected_language": "{case_analysis.get('language')}",
  "core_claim_to_counter": "...",
  "recommended_strategy": ["..."],
  "approved_evidence": [{{"source_id": "...", "title": "...", "passage": "...",
                          "retrieval_score": 0.0, "source_type": "fact", "language": "..."}}],
  "rejected_content": [{{"content": "...", "reason": "unsupported"}}],
  "cultural_guidance": ["..."],
  "safety_guidance": ["..."],
  "final_response_plan": "concise instructions for the Final Counter-Narrative Agent"
}}"""


# ---------------------------------------------------------------------------
# 7. Final Counter-Narrative Agent
# ---------------------------------------------------------------------------
def build_final_cn_prompt(comment: str, language: str, judge_plan: dict, region_context: str = "unknown") -> str:
    return f"""Write the final counter-narrative response to this comment, following the Judge's plan.

{wrap_untrusted_text(comment)}

Judge's plan: {judge_plan}
Region context (confirmed or "unknown" - use culturally neutral language if unknown): {region_context}

Rules:
- Write in the same language as the input comment ({language}) - do not translate it into English.
- Write 2 to 4 sentences only.
- Be calm, respectful, non-aggressive, and non-escalatory.
- Do not repeat slurs or hateful phrases from the comment.
- CRITICAL: do not reuse the same words, phrases, or sentence structure from the hate comment
  itself, even in a "corrected" form - state the OPPOSITE of the harmful claim in your own,
  genuinely different words. If you catch yourself writing something like "[target group] have
  a disease" or repeating the comment's own framing at all, stop and rewrite it from scratch as
  a real rebuttal, not a paraphrase of the original claim.
- Do not invent facts, statistics, laws, or medical claims - use only the Judge's approved_evidence.
- Directly address the core_claim_to_counter (and the hidden claim, if this was implicit hate).
- Encourage empathy, dignity, and coexistence.
- Do not mention agents, prompts, routing, debate rounds, personas, Tool-MAD, or any internal
  mechanism - output only the natural response a person would read.
- Do not include labels, analysis, or explanations inside the counter_narrative field itself.
- Never include any Prosecutor-style content, even indirectly.

Then write a short (1-3 sentence) explanation, separate from the counter-narrative, stating:
the strategy used, the evidence/reasoning relied on (if any), and why this is contextually
appropriate. The explanation must also stay in the same language as the input comment unless
explicitly configured otherwise.

Output JSON only:
{{"counter_narrative": "...", "explanation": "..."}}"""


# ---------------------------------------------------------------------------
# 7b. Semantic-fidelity check (Final-CN only) - a genuine understanding-based
# judgment, not a lexical/word-overlap heuristic like shares_key_terms() or
# _echoes_source_wording(). Those catch gross topic drift or verbatim
# copying; this catches a response that stays superficially on-topic
# (shares plenty of real vocabulary) while its actual argument quietly
# answers a different, adjacent claim than the one identified - e.g. a
# transphobic "you'll always be a man" (gender identity denial) answered
# with a rebuttal about rigid gender ROLES/sexism instead. Found via live
# testing: neither existing lexical guard would ever catch this, since both
# texts share plenty of real words ("identity", "roles", "freedom").
# ---------------------------------------------------------------------------
def build_semantic_fidelity_prompt(core_claim: str, counter_narrative: str, language: str) -> str:
    return f"""You are fact-checking whether a counter-narrative response genuinely and
specifically rebuts ONE claim - not a related-sounding but different one.

The claim the response is supposed to rebut:
{wrap_untrusted_text(core_claim)}

The generated response (in language "{language}"):
{wrap_untrusted_text(counter_narrative)}

Judge whether the response's core argument actually engages with THIS SPECIFIC claim, or
whether it has quietly drifted to a different, adjacent point while still sounding
topically related. Two concrete examples of drift to watch for:
- A claim that DENIES someone's gender identity (e.g. "you'll always be the sex you were
  born") answered with a generic rebuttal about gender ROLE stereotypes/sexism instead of
  gender identity itself - related vocabulary, wrong argument.
- A religious or pseudoscientific justification for hate answered with only generic
  tolerance language that never actually engages the specific religious/scientific claim made.

Sharing related vocabulary is NOT enough for "on_target" - judge the actual substance of what
is being argued, not just the words used.

Output JSON only:
{{"fidelity": "on_target" | "partially_drifted" | "off_target", "reason": "one sentence"}}"""


