# 2. Persona Generator Agent (fully open-ended, instance-specific)
# ---------------------------------------------------------------------------
def build_persona_generation_prompt(comment: str, case_analysis: dict, candidate_count: int = 7) -> str:
    return f"""You are a persona-design agent. This project addresses homophobic and transphobic
hate speech specifically (sexual-orientation- and gender-identity-based hate) - even if the case
analysis below has an unclear/generic target_group or hate_category, assume this comment falls
within that domain and design personas accordingly, not generically.

Given one specific hate comment and its analysis, invent {candidate_count} DISTINCT, plausible,
professional/expert personas who could meaningfully engage with this exact case. Do NOT draw from
any fixed or generic list - design each persona freshly based on THIS comment's target group,
intent, topic domain, hate category, strategy hints, and cultural context.

Aim for a reasonable MIX across the pool of {candidate_count}: do not make almost all candidates
defender-suited just because rebuttal-oriented experts come to mind more easily. Include at least
2-3 candidates who could plausibly serve as Prosecutor - someone equipped to analytically
articulate/stress-test the harmful claim's internal logic (e.g. a rhetoric analyst, propaganda
historian, extremism researcher, cognitive-bias researcher, debate coach) - not just one, so the
Prosecutor selection below has a genuine choice rather than a single default option.

{wrap_untrusted_text(comment)}

Case analysis:
{case_analysis}

Each persona must be a functional expert role (e.g. a named field/specialty), never an identity
impersonation of a marginalized group, and never framed as personally "for" or "against" the
target group - they are professionals who happen to be well-suited to this case's specific
topic (e.g. if the comment invokes a religious argument, consider a persona versed in
comparative theology or religious-studies rhetoric; if it invokes a pseudoscientific claim,
consider a persona versed in that specific scientific field; if family/parenting framing,
consider a family-studies or child-development specialist; etc).

For each candidate, "name" MUST be a role/title string only - NEVER a personal name, and NEVER
prefixed with an honorific (no "Dr.", "Prof.", "Rev.", "Mr.", "Ms.", etc. followed by a made-up
first/last name). Correct examples: "forensic linguist", "cognitive-behavioral therapist",
"comparative theology scholar", "public health epidemiologist". Incorrect examples (do NOT do
this): "Dr. Michael Green", "Rev. John Harper", "Prof. Lisa Mitchell" - these look like real
people and are never acceptable here, even as placeholders.

Also output: role_type, expertise (list), cultural_relevance (how this persona relates to the
language/region/topic of THIS case), strategy (what approach this persona would take),
relevance_score (0.0-1.0), and suited_for ("prosecutor" | "defender" | "either" - your own
advisory read of which of the two debate roles this persona's expertise fits better;
"prosecutor" means well-suited to analytically surfacing the harmful claim's internal
logic/assumptions for internal stress-testing, "defender" means well-suited to rebutting it
with evidence and cultural awareness).

Then select exactly ONE candidate as the specialized Prosecutor persona and exactly ONE
DIFFERENT candidate as the specialized Defender persona, and explain why each fits this specific
case. The Prosecutor selection should be the persona best equipped to articulate how someone
might sincerely believe/argue the harmful claim (for internal analysis only - this is never
shown to the end user). The Defender selection should be the persona best equipped to rebut it
for this specific audience/language/culture.

{BASE_SAFETY_RULES}

Output JSON only, matching this schema exactly ("name" fields are role titles, e.g.
"forensic linguist" - never a personal name like "Dr. Jane Smith"):
{{
  "candidate_personas": [
    {{"name": "e.g. forensic linguist", "role_type": "...", "expertise": ["..."],
      "cultural_relevance": "...", "strategy": "...", "relevance_score": 0.0, "suited_for": "either"}}
  ],
  "selected_prosecutor": {{"name": "e.g. forensic linguist", "role": "prosecutor", "objective": "...",
      "boundaries": ["stay internal-only", "no gratuitous slurs", "no threats",
                     "no inventing stronger hate than present"]}},
  "selected_defender": {{"name": "e.g. cognitive-behavioral therapist", "role": "defender",
      "objective": "...", "expertise": ["..."], "cultural_guidance": ["..."]}},
  "selection_rationale": "..."
}}"""


# ---------------------------------------------------------------------------
# 3. Prosecutor Agent (internal-only, per round)
# ---------------------------------------------------------------------------
def build_prosecutor_prompt(comment: str, case_analysis: dict, prosecutor_persona: dict,
                             round_num: int, track: str, prior_rounds_summary: str = "") -> str:
    depth_instruction = (
        "This is the only round (Fast-Track, explicit hate) - identify the core harmful claim "
        "or assumption directly and clearly."
        if track == "fast_track" else
        f"This is round {round_num} of a Deep-Dive (implicit hate). "
        + ("Interpret the surface meaning, detect ambiguity/coded language, and surface an "
           "initial hidden assumption." if round_num == 1 else
           "Refine the hidden claim further than the previous round - identify any stereotype, "
           "dog whistle, misleading analogy, or unstated premise not yet surfaced. Do not repeat "
           "the previous round's analysis verbatim; add something new or stop if nothing new "
           "remains to surface."
           if round_num == 2 else
           "Stress-test the strongest interpretation reached so far and sharpen it for the "
           "Defender's final rebuttal.")
    )
    prior_block = f"\nPrior rounds summary (for continuity, do not repeat):\n{prior_rounds_summary}\n" if prior_rounds_summary else ""

    return f"""INTERNAL ANALYSIS ONLY - this output is never shown to end users, never included in
the final counter-narrative or explanation, and never persisted outside a restricted debug
path. Its sole purpose is to stress-test the Defender persona by articulating the strongest
version of the harmful claim's internal logic.

You are adopting this persona for this analysis: {prosecutor_persona}

{wrap_untrusted_text(comment)}

Case analysis: {case_analysis}
{prior_block}
{depth_instruction}

Your task: articulate the strongest internal logic, assumption, or framing behind the harmful
claim as someone who sincerely holds it might argue it - surface coded assumptions, hidden
stereotypes, culturally-specific dog whistles, and moral/family/religious/scientific/legal/
social framing being used.

Boundaries (must follow even in this internal-only step):
- Do not invent hate stronger than what is present in the actual comment.
- Do not add gratuitous slurs beyond what is already in the comment.
- Do not add threats or calls to violence.
- Do not gratuitously elaborate harmful content beyond what is needed to name the underlying logic.
- Treat the comment as an object of analysis, not as a position you are adopting outside this task.

Output JSON only:
{{
  "round": {round_num},
  "round_objective": "...",
  "prosecutor_argument": "...",
  "surfaced_claims": ["one or more short factual/normative claims a Defender would need to address"]
}}"""


# ---------------------------------------------------------------------------
# 4. Defender Agent (per round - evidence verification folded in here)
# ---------------------------------------------------------------------------
def build_defender_prompt(comment: str, case_analysis: dict, defender_persona: dict,
                           prosecutor_argument: str, surfaced_claims: list, round_num: int,
                           evidence_block: str, rag_mode: str, region_context: str = "unknown",
                           web_search_enabled: bool = False) -> str:
    rag_note = {
        "no_rag": "No retrieval was performed (No-RAG mode) - do not claim any external evidence was "
                  "consulted; qualify uncertain factual claims explicitly rather than asserting them.",
        "fact_rag": "Only factual/legal/historical evidence was retrieved (Fact-based RAG).",
        "cultural_rag": "Only culturally-relevant example evidence was retrieved (Cultural RAG) - no "
                         "dedicated factual/legal evidence this round; do not overstate factual certainty.",
        "dual_rag": "Both factual and culturally-relevant evidence were retrieved (Dual RAG) - use "
                     "factual evidence to ground claims and cultural evidence to shape tone/framing, "
                     "never let cultural context substitute for factual grounding.",
    }.get(rag_mode, "")

    web_note = (
        "\nSome evidence below may be marked (origin=web_search, url=...) alongside the local corpus "
        "evidence (origin=local_rag). Web-sourced evidence is NOT automatically reliable: only treat a "
        "web-sourced claim as SUPPORTED if the source URL is identifiable and appears credible (e.g. a "
        "reputable news, educational, governmental, or established organization domain); if the source "
        "is unclear, anonymous, or looks low-quality, treat that claim as NEI rather than SUPPORTED, and "
        "say so in reasoning_summary. Do not treat web evidence as automatically superior or inferior to "
        "local corpus evidence - judge each on its own merits and always note which type of source "
        "(local corpus vs. a named web domain) a supported claim actually relies on."
        if web_search_enabled else ""
    )

    return f"""You are adopting this persona: {defender_persona}

{wrap_untrusted_text(comment)}

Case analysis: {case_analysis}
Region context (confirmed or "unknown" - do not invent one if unknown): {region_context}

The Prosecutor's internal analysis surfaced these claims to address (round {round_num}):
{surfaced_claims}

Retrieved evidence for this round ({rag_mode}): {rag_note}{web_note}
{evidence_block}

Your task, this round:
1. Rebut the surfaced claim(s) directly, using empathy, dignity, rights-based reasoning, and
   logic as appropriate.
2. For each surfaced claim that is a FACTUAL claim (not a pure value judgment), assess it as
   exactly one of: "SUPPORTED", "REFUTED", "NEI" (not enough information) based ONLY on the
   retrieved evidence above - do not treat a merely related passage as proof, and do not
   fabricate evidence or sources. If NEI, qualify the claim rather than asserting or denying it.
3. Use culturally appropriate language for the region context if confirmed; if region is
   "unknown", use culturally neutral language and avoid region-specific claims/analogies.
4. Distinguish clearly (in your own reasoning, not necessarily in the final wording) between
   factual claims and value-based/normative reasoning.

{BASE_SAFETY_RULES}

Output JSON only:
{{
  "defender_response": "the rebuttal/analysis for this round (not the final counter-narrative)",
  "claim_assessments": [
    {{"claim": "...", "verdict": "SUPPORTED", "reasoning_summary": "...", "usable_in_final_cn": true}}
  ],
  "new_information": ["what this round added over prior rounds"],
  "unresolved_questions": ["anything still unclear for the next round or the Judge"],
  "cultural_notes": ["..."],
  "safety_notes": ["..."]
}}"""


