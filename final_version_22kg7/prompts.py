def _infer_claim_type_without_kg(comment: str, judge_plan: dict, case_analysis: dict = None) -> str:
    """Lightweight non-KG claim-type hint for the no_kg ablation prompt.

    It preserves v22kg6 language/style controls without constructing or passing
    the Counter-Narrative KG. This is intentionally simpler than the KG builder
    and is used only when KG is disabled.
    """
    case_analysis = case_analysis or {}
    parts = [
        comment or "",
        str((judge_plan or {}).get("core_claim_to_counter") or ""),
        str((judge_plan or {}).get("final_response_plan") or ""),
        " ".join(case_analysis.get("strategy_hint") or []),
        " ".join(case_analysis.get("intent") or []),
        case_analysis.get("hidden_claim") or "",
        case_analysis.get("target_group") or "",
    ]
    text = " ".join(parts).lower()
    if any(k in text for k in ["baby", "child", "future child", "family", "parent", "abortion", "reject"]):
        return "child/family rejection based on orientation; abortion/family rejection based on possible orientation"
    if any(k in text for k in ["cure", "convert", "change", "free from", "liberated", "liberation"]):
        return "conversion/change framing"
    if any(k in text for k in ["relationship", "couple", "marriage", "same-sex", "same sex", "love"]):
        return "same-sex relationship stigma"
    if any(k in text for k in ["disease", "illness", "mental", "disorder", "sick", "insane", "abnormal", "defect"]):
        return "disease/pathology framing"
    if any(k in text for k in ["curse", "sin", "god", "religion", "religious", "theology"]):
        return "curse_or_religion_framing"
    if any(k in text for k in ["crime", "criminal", "predator", "danger", "threat"]):
        return "crime_generalization"
    if any(k in text for k in ["shut up", "silent", "voice", "speak", "silence"]):
        return "silencing"
    return "generic dignity rebuttal"


