# 7. Final Counter-Narrative Agent
#
# v22b (2026-08-10): an experimental, structurally-improved rewrite of this
# prompt, aimed at Mistral full_pipeline quality specifically (see
# docs/07_EVALUATION_STRATEGY.md's "v22b" section for the full rationale and
# the small-sample qualitative comparison this needs before any full
# benchmark run). Selected via the module-level FINAL_CN_STYLE toggle below
# (default "v20", unchanged) or an explicit `style=` argument - deliberately
# NOT a new parameter threaded through final_cn_agent.py/pipeline.py, so
# neither of those files (both on the locked v20-identical generation-path
# manifest, see tests/test_generation_path_frozen.py) needs to change at
# all to support this experiment; main.py's --final-cn-style flag sets this
# module global once, before any generation happens, and everything
# downstream picks it up transparently through the existing, unchanged call
# chain. This keeps the v22b experiment isolated to exactly one file
# (prompts.py, already outside that manifest since v22a).
# ---------------------------------------------------------------------------
FINAL_CN_STYLE = "v20"

# Basque and Tamil showed greater fluency/terminology risk in earlier
# outputs (see docs/07_EVALUATION_STRATEGY.md, language_quality.py findings
# from live testing - e.g. garbled Tamil transliterations of LGBTQ+ terms) -
# v22b asks specifically for simpler, clearer wording in these two.
_SIMPLE_WORDING_LANGUAGES = {"ta", "eu"}

_FINAL_CN_LANGUAGE_NAMES = {"en": "English", "ta": "Tamil", "eu": "Basque",
                             "es": "Spanish", "it": "Italian"}


def _resolve_final_cn_region_code(language: str, region_context: str) -> str:
    """English is the only language this project splits by region
    (dataset_loader._normalize_record's "region" field, confirmed/inferred
    as "Indian"/"European"/"unknown" - see config.DATASET_CULTURAL_REGION).
    The pipeline itself only ever passes language="en" for English text;
    "en_EUR"/"en_IN" are a reporting/evaluation-side label (see
    evaluation.py Stage 6/7/8) applied by combining language+region - this
    resolves that same combination for use INSIDE the prompt text itself,
    so the model gets the same regional vocabulary the thesis reports use,
    even though the underlying `language` argument never literally changes."""
    if language != "en":
        return language
    if region_context == "Indian":
        return "en_IN"
    if region_context == "European":
        return "en_EUR"
    return "en"


