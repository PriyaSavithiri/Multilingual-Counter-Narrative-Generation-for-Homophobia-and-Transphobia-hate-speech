# validated pattern by itself.
# ---------------------------------------------------------------------------
def build_unsafe_term_validation_prompt(term: str, language: str, example_snippets: list,
                                         hate_association_score: float = None) -> str:
    language_display = _LANGUAGE_DISPLAY_NAMES.get(language, language)
    examples_block = "\n".join(f"- {wrap_untrusted_text(s)}" for s in example_snippets) or "(no examples available)"
    score_note = f"{hate_association_score:.2f}" if hate_association_score is not None else "not available"
    return f"""You are reviewing a CANDIDATE term or phrase, drawn statistically from a hate-speech
dataset, to suggest whether it should be treated as an unsafe keyword for automatic content
flagging. Your judgment is a SUGGESTION for a human reviewer, not a final decision - when unsure,
say so rather than guessing toward either extreme.

Term/phrase being reviewed (language: {language_display}): {wrap_untrusted_text(term)}
This term appeared more often in hate-speech comments than in safe counter-narrative replies in
this project's dataset (hate-association score: {score_note} - higher means more hate-associated,
NOT proof of being unsafe by itself; many ordinary topic words score highly too, purely because
the dataset naturally discusses a topic more in the hateful comments than in the calm replies).

Example hate-speech sentences where this term appeared (for context only - judge the TERM, not
whether these specific sentences are hateful, that's already established):
{examples_block}

Apply these rules strictly:
- Do NOT mark a neutral identity label as unsafe. Words that simply name a sexual orientation or
  gender identity (e.g. gay, lesbian, trans, bisexual, queer, homosexual, or their equivalents in
  {language_display}) are NEVER unsafe by themselves, even if they appear often in hate speech -
  the dataset naturally discusses these identities when attacking them, which is not the same as
  the word itself being harmful.
- Mark "unsafe" ONLY if the term is inherently harmful or strongly harmful essentially regardless
  of context (e.g. a slur, a call to violence, an explicit dehumanizing label).
- If the term is only harmful depending on how it's used (e.g. a clinical-sounding word that
  becomes harmful specifically in a "disease"/"disorder" framing), mark "unsafe_only_in_context" -
  not "unsafe".
- If you are not confident which category applies, mark "unclear" and set needs_human_review to
  true - do not force a guess.

{BASE_SAFETY_RULES}

Output JSON only, with exactly these fields:
{{"decision": "unsafe" | "unsafe_only_in_context" | "neutral_identity_term" | "neutral/general" | "unclear",
  "category": "violence_or_threat" | "dehumanisation" | "disease_or_pathology_framing" | "criminalisation" |
              "sexual_predation_or_grooming_framing" | "exclusion_or_silencing" | "insult_or_slur" |
              "neutral_identity_term" | "unclear",
  "severity": "low" | "medium" | "high",
  "notes": "one short sentence explaining the decision",
  "needs_human_review": true | false}}"""


